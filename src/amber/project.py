"""``amber init``: create the project layout (``docs/03-cli-spec.md``, ``01-architecture.md``).

Idempotent: existing files are kept (and re-validated) unless ``force`` is given.
"""

from __future__ import annotations

from pathlib import Path

from pydantic import BaseModel, ConfigDict

from amber.config import parse_config
from amber.models.ids import ResolvedModels, resolve_model_ids
from amber.util.paths import CONFIG_FILENAME, HOME_SUBDIRS, amber_home
from amber.util.time import utcnow

GITIGNORE_ENTRIES = (".amber/", "*.env")


class InitResult(BaseModel):
    model_config = ConfigDict(extra="forbid")

    root: str
    home: str
    config_path: str
    created: list[str]
    kept: list[str]
    synthesis_model: str
    judgment_model: str
    models_source: str


def render_config_template(name: str, models: ResolvedModels) -> str:
    """The ``amber.toml`` written by ``amber init``."""
    verify = "" if models.source == "api" else "   # verify: default, not resolved via the API"
    today = utcnow().date().isoformat()
    return f"""# Amber project configuration — generated by `amber init` on {today}.
# Reference: https://github.com/enestanerr/Amber#configuration. Never put credentials here; use
# environment variables.

[project]
name = "{name}"

[models]
backend = "auto"                  # auto | anthropic | cli | recorded
synthesis = "{models.synthesis}"{verify}
judgment = "{models.judgment}"{verify}

# One table per MCP server the compiled programs may call. stdio: command + args (+ env);
# streamable HTTP: url = "http://...".
[servers]
# [servers.shop]
# command = "uv"
# args = ["run", "examples/weekly-report/server_shop.py"]
# env = {{ AMBER_SCENARIO = "A" }}

[budgets]
max_calls_factor = 2.0            # multiplier over the max recorded call count
max_llm_tokens = 40000            # per run; applies without a recompile
wall_clock_s = 600

[guards]
min_confidence = 0.5

[fallback]
daily_budget = 3
"""


def _ensure_gitignore(root: Path, created: list[str], kept: list[str]) -> None:
    path = root / ".gitignore"
    if path.exists():
        text = path.read_text(encoding="utf-8")
        present = {line.strip() for line in text.splitlines()}
        missing = [e for e in GITIGNORE_ENTRIES if e not in present]
        if missing:
            suffix = "" if text.endswith("\n") or not text else "\n"
            block = suffix + "\n# Amber runtime state\n" + "\n".join(missing) + "\n"
            path.write_text(text + block, encoding="utf-8", newline="\n")
            created.append(".gitignore (entries)")
        else:
            kept.append(".gitignore")
    else:
        path.write_text(
            "# Amber runtime state\n" + "\n".join(GITIGNORE_ENTRIES) + "\n",
            encoding="utf-8",
            newline="\n",
        )
        created.append(".gitignore")


def init_project(root: Path, *, force: bool = False) -> InitResult:
    """Create ``.amber/`` (with subdirs), ``amber.toml`` and ``.gitignore`` entries under *root*."""
    root = root.resolve()
    root.mkdir(parents=True, exist_ok=True)
    created: list[str] = []
    kept: list[str] = []

    home = amber_home(root)
    if home.exists():
        kept.append(str(home.relative_to(root)) if home.is_relative_to(root) else str(home))
    else:
        created.append(str(home.relative_to(root)) if home.is_relative_to(root) else str(home))
    home.mkdir(parents=True, exist_ok=True)
    for sub in HOME_SUBDIRS:
        (home / sub).mkdir(exist_ok=True)
    # Belt and braces: the state directory ignores itself even if the project .gitignore
    # is edited later.
    (home / ".gitignore").write_text("*\n", encoding="utf-8", newline="\n")

    config_path = root / CONFIG_FILENAME
    if config_path.exists() and not force:
        models = _models_from_existing(config_path)
        kept.append(CONFIG_FILENAME)
    else:
        models = resolve_model_ids()
        text = render_config_template(root.name, models)
        parse_config(text, source=CONFIG_FILENAME)  # self-check: template must validate
        config_path.write_text(text, encoding="utf-8", newline="\n")
        created.append(CONFIG_FILENAME)

    _ensure_gitignore(root, created, kept)

    return InitResult(
        root=str(root),
        home=str(home),
        config_path=str(config_path),
        created=created,
        kept=kept,
        synthesis_model=models.synthesis,
        judgment_model=models.judgment,
        models_source=models.source,
    )


def _models_from_existing(config_path: Path) -> ResolvedModels:
    """Re-validate an existing config (secret lint, schema) and report its model IDs."""
    cfg = parse_config(config_path.read_text(encoding="utf-8"), source=str(config_path))
    return ResolvedModels(cfg.models.synthesis, cfg.models.judgment, "defaults")
